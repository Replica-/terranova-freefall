#!/usr/bin/env bash
# build-shaders.sh -- compiles the screen filter shaders in port/video/shaders/ to SPIR-V (Vulkan) and
# DXIL (Direct3D 12) and writes them as C headers next to their sources. The headers are kept in
# the repository, so building the game doesn't need this; run it after changing a shader.
# Needs Python 3 and DXC (github.com/microsoft/DirectXShaderCompiler releases): DXC=/path/to/dxc.
set -e
DXC=${DXC:-dxc}
cd "$(dirname "$0")/../port/video/shaders"

header() {     # header <file> <name> <source>
    python3 - "$1" "$2" "$3" > "$1.h" <<'PY'
import sys
path, name, src = sys.argv[1:]
data = open(path, 'rb').read()
print('/* generated by tools/build-shaders.sh from %s -- do not edit */' % src)
print('static const unsigned char %s[] = {' % name)
for i in range(0, len(data), 16):
    print('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
print('};')
print('static const unsigned int %s_len = %d;' % (name, len(data)))
PY
    rm -f "$1"
}

# a DXC without SPIR-V (the Windows SDK's): DXIL only, the SPIR-V headers left as they are
spirv=1
echo 'float4 main() : SV_Target { return 0; }' > _probe.hlsl
"$DXC" -nologo -T ps_6_0 -E main -spirv _probe.hlsl -Fo _probe.spv >/dev/null 2>&1 || spirv=0
rm -f _probe.hlsl _probe.spv
[ $spirv = 1 ] || echo "build-shaders.sh: this DXC makes no SPIR-V; DXIL only" >&2

build() {      # build <source> <name> <profile>
    echo "$1"
    if [ $spirv = 1 ]; then
        "$DXC" -nologo -T "$3" -E main -O3 -spirv -fspv-target-env=vulkan1.0 "$1" -Fo "$2.spv"
        header "$2.spv" "${2}_spv" "$1"
    fi
    "$DXC" -nologo -T "$3" -E main -O3 -Qstrip_debug -Qstrip_reflect "$1" -Fo "$2.dxil"
    header "$2.dxil" "${2}_dxil" "$1"
}

for src in *.frag.hlsl; do
    build "$src" "${src%.frag.hlsl}" ps_6_0
done
for src in *.vert.hlsl; do     # (name_vert: a vertex shader beside its fragment one)
    build "$src" "${src%.vert.hlsl}_vert" vs_6_0
done
